def demo_ai(message):
    """
    Works without an API.
    This is intentionally a demo engine, not a real LLM.
    """

    text = message.lower()

    if "python" in text:
        return (
            "PocketAura Demo AI:\n\n"
            "Python is a beginner-friendly programming language. "
            "For learning Python, start with variables, conditions, "
            "loops, functions, lists, dictionaries and modules."
        )

    if "study" in text:
        return (
            "PocketAura Study Assistant:\n\n"
            "Try this study cycle:\n"
            "1. Learn the concept.\n"
            "2. Write short notes.\n"
            "3. Practice questions.\n"
            "4. Explain the topic yourself.\n"
            "5. Revise later."
        )

    if "resume" in text:
        return (
            "PocketAura Resume Assistant:\n\n"
            "Use this structure:\n"
            "Name → Contact → Summary → Education → Skills → "
            "Projects → Experience → Certifications."
        )

    return (
        "PocketAura Demo AI:\n\n"
        f"You asked: {message}\n\n"
        "This response is generated by PocketAura's local demo "
        "engine. Configure OPENROUTER_API_KEY to connect a real "
        "AI model."
    )


def real_ai(message):
    if not OPENROUTER_API_KEY:
        return demo_ai(message)

    try:
        response = requests.post(
            "https://openrouter.ai/api/v1/chat/completions",
            headers={
                "Authorization": f"Bearer {OPENROUTER_API_KEY}",
                "Content-Type": "application/json",
                "HTTP-Referer": os.environ.get(
                    "SITE_URL",
                    "http://localhost:5000"
                ),
                "X-Title": "PocketAura"
            },
            json={
                "model": OPENROUTER_MODEL,
                "messages": [
                    {
                        "role": "system",
                        "content": (
                            "You are PocketAura, a helpful AI assistant. "
                            "Give accurate, clear and practical answers."
                        )
                    },
                    {
                        "role": "user",
                        "content": message
                    }
                ]
            },
            timeout=60
        )

        data = response.json()

        if response.status_code != 200:
            return f"AI service error: {data}"

        return data["choices"][0]["message"]["content"]

    except Exception as e:
        return f"AI connection failed: {e}"


